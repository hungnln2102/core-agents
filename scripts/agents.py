"""Build, validate and install the Codex adapters from the constitutions."""
from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
import re
import sys
import tempfile
import tomllib

ROOT = Path(__file__).resolve().parents[1]
MANAGED = "# Generated by scripts/agents.py. Edit rules/ and regenerate.\n"
ROLES = {
    "orchestrator": "Coordinate multi-role work, check approval and verify delivery.",
    "lead-planner": "Investigate requirements, plan changes and define acceptance criteria.",
    "backend-specialist": "Design and implement APIs, integrations and data workflows.",
    "frontend-lead": "Design or implement interfaces with the project's design system.",
    "finance-specialist": "Reconcile financial data and review monetary workflows.",
    "security-auditor": "Review authorization, secrets and defensive security controls.",
    "qa-automation": "Verify behavior with focused tests and report coverage limits.",
}
TRANSACTION_ROLES = {"backend-specialist", "finance-specialist"}
FORBIDDEN = re.compile(
    r"(?im)(?:\b[A-Z]:[/\\]|file:///|(?<![\w.])~[/\\]|"
    r"(?<!\w)/(?:home|Users|var/www)/|//\s*turbo-all|\btask_boundary\b)"
)
MARKDOWN_LINK = re.compile(r"(?<!!)\[[^\]\n]+\]\(([^)\s]+)\)")


def read(path: Path) -> str:
    data = path.read_bytes()
    if data.startswith(b"\xef\xbb\xbf"):
        raise ValueError(f"UTF-8 BOM: {path}")
    value = data.decode("utf-8")
    if "\ufffd" in value:
        raise ValueError(f"Replacement character: {path}")
    return value.replace("\r\n", "\n")


def render() -> dict[str, str]:
    common = read(ROOT / "rules/AGENTS.md").strip()
    acid = read(ROOT / "rules/references/acid-transactions.md").strip()
    configs = {}
    for role, description in ROLES.items():
        name = f"{role}-agent"
        instructions = [common, read(ROOT / "rules/roles" / f"{role}.md").strip()]
        if role in TRANSACTION_ROLES:
            instructions.append(acid)
        configs[f"{name}.toml"] = (
            MANAGED
            + f"name = {json.dumps(name)}\n"
            + f"description = {json.dumps(description)}\n"
            + "developer_instructions = "
            + json.dumps("\n\n".join(instructions), ensure_ascii=False)
            + "\n"
        )
    return configs


def check(configs: dict[str, str]) -> None:
    role_files = {path.stem for path in (ROOT / "rules/roles").glob("*.md")}
    if role_files != ROLES.keys():
        raise ValueError("Expected exactly seven role constitutions")
    agent_files = {path.name for path in (ROOT / "agents").glob("*.toml")}
    if agent_files != configs.keys():
        raise ValueError("Expected exactly seven generated agent files")
    for name, expected in configs.items():
        path = ROOT / "agents" / name
        if read(path) != expected:
            raise ValueError(f"Stale adapter: {name}. Run python scripts/agents.py build")
        parsed = tomllib.loads(expected)
        if parsed["name"] != path.stem or FORBIDDEN.search(parsed["developer_instructions"]):
            raise ValueError(f"Non-portable adapter: {name}")
    documents = [ROOT / "README.md", *ROOT.glob("rules/**/*.md"), *ROOT.glob("docs/**/*.md")]
    for path in documents:
        for link in MARKDOWN_LINK.findall(read(path)):
            if link.startswith(("https://", "http://", "#")):
                continue
            target = (path.parent / link.split("#", 1)[0]).resolve()
            if not target.is_relative_to(ROOT) or not target.exists():
                raise ValueError(f"Invalid internal link in {path.relative_to(ROOT)}: {link}")
    codex, other, marketplace = (
        json.loads(read(ROOT / name))
        for name in (".codex-plugin/plugin.json", "plugin.json", ".agents/plugins/marketplace.json")
    )
    if codex["name"] != other["name"] or codex["version"] != other["version"]:
        raise ValueError("Plugin manifests disagree")
    if marketplace["plugins"][0]["name"] != codex["name"]:
        raise ValueError("Marketplace plugin name differs from manifest")
    if "skills" in codex or "skills" in other or (ROOT / "skills").exists():
        raise ValueError("Role expertise must not be published as a skill catalog")


def atomic_write(path: Path, value: str) -> None:
    try:
        with tempfile.NamedTemporaryFile(
            mode="w", encoding="utf-8", newline="\n", dir=path.parent, delete=False
        ) as pending:
            temporary = Path(pending.name)
            pending.write(value)
        temporary.replace(path)
    finally:
        if "temporary" in locals():
            temporary.unlink(missing_ok=True)


def install(configs: dict[str, str], directory: Path) -> int:
    directory = directory.expanduser()
    if directory.is_symlink() or directory.resolve() == (ROOT / "agents").resolve():
        raise ValueError("Choose a regular agents directory outside the checkout")
    blocked = [
        name for name in configs
        if (directory / name).is_symlink()
        or ((directory / name).exists() and not read(directory / name).startswith(MANAGED))
    ]
    if blocked:
        raise ValueError(f"Existing unmanaged agent files: {', '.join(blocked)}")
    directory.mkdir(parents=True, exist_ok=True)
    changed = 0
    for name, value in configs.items():
        path = directory / name
        if path.exists() and read(path) == value:
            continue
        atomic_write(path, value)
        changed += 1
    return changed


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    commands = parser.add_subparsers(dest="command", required=True)
    commands.add_parser("build", help="Regenerate tracked Codex agent definitions")
    commands.add_parser("check", help="Validate sources, manifests and tracked definitions")
    installer = commands.add_parser("install", help="Install definitions without replacing other agents")
    installer.add_argument("--directory", type=Path, help="Destination agents directory")
    args = parser.parse_args()
    try:
        configs = render()
        if args.command == "build":
            for name, value in configs.items():
                atomic_write(ROOT / "agents" / name, value)
        check(configs)
        if args.command == "install":
            root = Path(os.environ["CODEX_HOME"]) if "CODEX_HOME" in os.environ else Path.home() / ".codex"
            count = install(configs, args.directory or root / "agents")
            print(f"Updated {count} of {len(configs)} agent definitions.")
        else:
            print(f"Validated {len(configs)} agent definitions.")
    except (OSError, ValueError) as error:
        print(error, file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
